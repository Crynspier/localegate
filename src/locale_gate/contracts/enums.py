"""Enumerations and stable reason codes for LocaleGate contracts."""

from __future__ import annotations

from enum import StrEnum

CONTRACT_VERSION = "1.0"


class LocaleCode(StrEnum):
    """Supported BCP 47 locale tags."""

    HR_HR = "hr-HR"
    EN_US = "en-US"
    EN_GB = "en-GB"


class ToolName(StrEnum):
    """Allowlisted simulated write tools."""

    SUBMIT_EXPENSE = "submit_expense"
    SCHEDULE_EVENT = "schedule_event"


class ProposalDecision(StrEnum):
    """Untrusted decision proposed by the model."""

    PROPOSE = "propose"
    CLARIFY = "clarify"
    NO_ACTION = "no_action"


class GateDecisionStatus(StrEnum):
    """Authoritative decision produced by the deterministic gate."""

    EXECUTED = "EXECUTED"
    AWAITING_CONFIRMATION = "AWAITING_CONFIRMATION"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
    BLOCKED = "BLOCKED"
    NO_ACTION = "NO_ACTION"
    MODEL_ERROR = "MODEL_ERROR"


class ParseStatus(StrEnum):
    """Outcome of a deterministic parser on an evidence span."""

    PARSED = "PARSED"
    AMBIGUOUS = "AMBIGUOUS"
    INVALID = "INVALID"
    MISSING = "MISSING"
    UNSUPPORTED = "UNSUPPORTED"


class RoleBindingStatus(StrEnum):
    """Outcome of deterministic semantic field-role binding verification (§5.2)."""

    VERIFIED = "VERIFIED"
    AMBIGUOUS = "AMBIGUOUS"
    MISMATCH = "MISMATCH"
    NOT_APPLICABLE = "NOT_APPLICABLE"


class OffsetUnit(StrEnum):
    """Explicit character offset unit for resolved evidence spans (§5.3)."""

    UNICODE_CODE_POINT = "unicode_code_point"


class ConfirmationStatus(StrEnum):
    """User confirmation lifecycle state (distinct from business approval)."""

    PENDING = "pending"
    CONFIRMED = "confirmed"
    REJECTED = "rejected"
    EXPIRED = "expired"
    NOT_APPLICABLE = "not_applicable"


class BusinessApprovalStatus(StrEnum):
    """Simulated business workflow state after user confirmation."""

    PENDING_MANAGER_APPROVAL = "pending_manager_approval"
    NOT_APPLICABLE = "not_applicable"


class ExpenseCategory(StrEnum):
    """Allowlisted expense categories."""

    TRAVEL = "travel"
    MEALS = "meals"
    LODGING = "lodging"
    OFFICE_SUPPLIES = "office_supplies"
    SOFTWARE = "software"
    CLIENT_ENTERTAINMENT = "client_entertainment"
    OTHER = "other"


